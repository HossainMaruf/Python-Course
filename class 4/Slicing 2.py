# Negative Slicing
names = ['Shahrukh', 'Salman', 'Amir', 'Saif Ali Khan', 'Tushar', 'Hritik', 'Sakib Khan']
print(names[0:10]) # Entire List
print(names[-1:0:-1])
# Positive step means forward
# Negative step means reverse
print(names[-1:-2:-1])
print(names[-1::-1])
print(names[::-1]) # Reverse a list