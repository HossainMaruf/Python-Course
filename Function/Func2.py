def add(num1, num2):
    return num1 + num2;

def sub(num1, num2):
    return num1 - num2;

def mul(num1, num2):
    return num1 * num2;

def div(num1, num2):
    return num1 / num2;

def power(num1, num2):
    return num1 ** num2;

num1 = 10
num2 = 3

result = add(num1, num2)
print(result)

result = sub(num1, num2)
print(result)

result = mul(num1, num2)
print(result)

result = div(num1, num2)
print(result)

result = power(num1, num2)
print(result)