'''
Formulae:
Area = PI * (r^2)
Perimeter = 2 * PI * r
'''

radius = 10.4
PI = 3.14159

diameter = 2 * radius
area = PI * radius * radius
perimeter = 2 * PI * radius

print(diameter, area, perimeter)

# ROUND function in python
# ROUND function return 2 decimel places
print(round(diameter, 2), round(area, 2), round(perimeter, 2))
